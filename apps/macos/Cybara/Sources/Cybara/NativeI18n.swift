    static func t(_ key: String) -> String {
        let locale = normalize(Locale.current.identifier)
        return catalogs[locale]?[key] ?? catalogs["en"]?[key] ?? key
    }

    private static func normalize(_ value: String) -> String {
        let lower = value.replacingOccurrences(of: "_", with: "-").lowercased()
        if lower.hasPrefix("es") { return "es" }
        if lower.hasPrefix("zh-hant") || lower.hasPrefix("zh-tw") || lower.hasPrefix("zh-hk") || lower.hasPrefix("zh-mo") { return "zh-TW" }
        if lower.hasPrefix("zh") { return "zh-CN" }
        if lower.hasPrefix("ja") { return "ja" }
        if lower.hasPrefix("fr") { return "fr" }
        if lower.hasPrefix("de") { return "de" }
        if lower.hasPrefix("ko") { return "ko" }
        if lower.hasPrefix("pt") { return "pt-BR" }
        if lower.hasPrefix("it") { return "it" }
        if lower.hasPrefix("nl") { return "nl" }
        if lower.hasPrefix("pl") { return "pl" }
        if lower.hasPrefix("tr") { return "tr" }
        if lower.hasPrefix("vi") { return "vi" }
        if lower.hasPrefix("id") { return "id" }
        if lower.hasPrefix("th") { return "th" }
        if lower.hasPrefix("hi") { return "hi" }
        if lower.hasPrefix("ru") { return "ru" }
        if lower.hasPrefix("uk") { return "uk" }
        if lower.hasPrefix("sv") { return "sv" }
        if lower.hasPrefix("da") { return "da" }
        if lower.hasPrefix("fi") { return "fi" }
        if lower.hasPrefix("ar") { return "ar" }
        return "en"
    }

